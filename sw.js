self.addEventListener("install", async () => {
    const cache = await caches.open(CACHES[0].name);
    await cache.addAll(CACHES[0].list);
    console.log("SW - cache ADDED: ", CACHES[0].name);
});

self.addEventListener("activate", async () => {
    const cachesKeys = await caches.keys();

    const allowedCacheNames = new Set(CACHES.map(c => c.name));
    const deletePromises = cachesKeys.map(async (key) => {
        if (!allowedCacheNames.has(key)) {
            await caches.delete(key);
            console.log("SW - cache DELETED: ", key);
        }
    });

    await Promise.all(deletePromises);
    console.log("SW - Successfully activated!");
});

self.addEventListener("fetch", event => {
    event.respondWith(caches.match(event.request).then(cachedResponse => {
        return cachedResponse || fetch(event.request);
    }));
});

self.addEventListener("message", async (event) => {
    if (event.data) {
        let answerStr, returnError;
        switch (event.data.key) {
            case "PROKACHAIKA_CACHE":
                if (event.data.value === true) {
                    const cache = await caches.open(CACHES[1].name);
                    await cache.addAll(CACHES[1].list);
                    answerStr = "Изображения насосов добавлены в кеш";
                    console.log("SW - NEW cache added: ", CACHES[1].name);
                } else {
                    await caches.delete(CACHES[1].name);
                    answerStr = "Изображения насосов удалены из кеша";
                }
            break;
        }
        if (event.ports[0]){
            if(returnError){
                // Ошибка в UI в port1
                event.ports[0].postMessage({
                    error: returnError
                });
            } else if(answerStr !== ""){
                    // Ответ в UI в port1
                    event.ports[0].postMessage({
                        answer: answerStr
                    });
            }
        }
    }
});